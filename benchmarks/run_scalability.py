def run_parallel_strategy_experiment(limit: int = EXPERIMENT_LIMIT, block_size: int = 10_000, threads: tuple[int, ...] = THREAD_COUNTS, trials: int = EXPERIMENT_TRIALS) -> list[dict[str, object]]:
    serial = binary("sieve_serial")
    openmp = binary("sieve_openmp")
    serial_samples = [run([str(serial), str(limit), "0", str(TIMING_REPETITIONS)], limit) for _ in range(trials)]
    serial_median_ms = statistics.median(float(sample["execution_time_ms"]) for sample in serial_samples)
    rows: list[dict[str, object]] = []

    for strategy_name, strategy_suffix in (("serial", None), ("naive_openmp", "naive"), ("block_openmp", "block")):
        if strategy_name == "serial":
            rows.append({
                "n": limit,
                "strategy": "serial",
                "threads": 1,
                "block_size": block_size,
                "prime_count": serial_samples[0]["prime_count"],
                "median_execution_time_ms": round(serial_median_ms, 6),
                "same_strategy_speedup": 1.0,
                "same_strategy_efficiency": 1.0,
                "serial_vs_parallel_speedup": 1.0,
                "trial_count": trials,
            })
            continue

        per_thread_samples: dict[int, list[dict[str, object]]] = {}
        for thread_count in threads:
            samples = [
                run(
                    [str(openmp), str(limit), str(thread_count), "0", str(TIMING_REPETITIONS), str(block_size), "static", strategy_suffix],
                    limit,
                    thread_count,
                )
                for _ in range(trials)
            ]
            per_thread_samples[thread_count] = samples

        baseline_median_ms = statistics.median(
            float(sample["execution_time_ms"]) for sample in per_thread_samples[1]
        )

        for thread_count in threads:
            samples = per_thread_samples[thread_count]
            prime_count = samples[0]["prime_count"]
            times_ms = [float(sample["execution_time_ms"]) for sample in samples]
            median_ms = statistics.median(times_ms)
            same_strategy_speedup = baseline_median_ms / median_ms if median_ms > 0 else 0.0
            same_strategy_efficiency = same_strategy_speedup / thread_count if thread_count > 0 else 0.0
            serial_vs_parallel_speedup = serial_median_ms / median_ms if median_ms > 0 else 0.0
            rows.append({
                "n": limit,
                "strategy": strategy_name,
                "threads": thread_count,
                "block_size": block_size,
                "prime_count": prime_count,
                "median_execution_time_ms": round(median_ms, 6),
                "same_strategy_speedup": round(same_strategy_speedup, 6),
                "same_strategy_efficiency": round(same_strategy_efficiency, 6),
                "serial_vs_parallel_speedup": round(serial_vs_parallel_speedup, 6),
                "trial_count": trials,
                "times_ms": [round(time_ms, 6) for time_ms in times_ms],
            })

    return rows


