"""Generate the canonical repeated strong-scaling benchmark bundle."""

import csv
import json
import os
import platform
import statistics
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
BIN_DIR = ROOT / "backend" / "bin"
RESULTS_DIR = ROOT / "results"
LIMITS = (100_000, 1_000_000, 10_000_000, 100_000_000)
THREAD_COUNTS = (1, 2, 4, 8)
BLOCK_SIZES = (1_000, 10_000, 100_000, 1_000_000)
TRIALS = 7
TIMING_REPETITIONS = 20
EXPERIMENT_TRIALS = 5
EXPERIMENT_LIMIT = 100_000_000
EXPECTED_PRIME_COUNTS = {
    100_000: 9_592,
    1_000_000: 78_498,
    10_000_000: 664_579,
    100_000_000: 5_761_455,
}


def derived_metrics(serial_time_s: float, parallel_time_s: float, threads: int) -> dict[str, float]:
    if serial_time_s <= 0 or parallel_time_s <= 0 or threads < 1:
        raise ValueError("times and thread count must be positive")
    speedup = serial_time_s / parallel_time_s
    efficiency = speedup / threads
    return {
        "speedup": speedup,
        "efficiency": efficiency,
        "efficiency_percent": efficiency * 100,
        "cost_s": threads * parallel_time_s,
    }


def binary(name: str) -> Path:
    suffix = ".exe" if sys.platform == "win32" else ""
    path = BIN_DIR / f"{name}{suffix}"
    if not path.is_file():
        raise FileNotFoundError(f"Missing {path}. Build the C++ binaries first.")
    return path


def run(command: list[str], limit: int, expected_threads: int | None = None) -> dict[str, object]:
    completed = subprocess.run(command, check=True, capture_output=True, text=True)
    result = json.loads(completed.stdout)
    if result["prime_count"] != EXPECTED_PRIME_COUNTS[limit]:
        raise RuntimeError(f"Incorrect prime count for {command}: {result['prime_count']}")
    if expected_threads is not None and result.get("actual_threads") != expected_threads:
        raise RuntimeError(f"OpenMP team mismatch for {command}: {result.get('actual_threads')}")
    if result["execution_time_ms"] <= 0:
        raise RuntimeError(f"Non-positive timed result for {command}: {result['execution_time_ms']}")
    return result


def measure(command: list[str], limit: int, expected_threads: int | None = None) -> list[dict[str, object]]:
    run(command, limit, expected_threads)  # Unmeasured warm-up.
    return [run(command, limit, expected_threads) for _ in range(TRIALS)]


def seconds(samples: list[dict[str, object]]) -> list[float]:
    return [float(sample["execution_time_ms"]) / 1000 for sample in samples]


def write_markdown(rows: list[dict[str, object]], path: Path) -> None:
    lines = [
        "# Canonical Benchmark Results",
        "",
        "Generated by `python benchmarks/run_scalability.py`. Times are median native computation seconds; see `benchmark_trials.csv` for raw samples.",
        "",
        "| N | Threads | Prime count | Serial time (s) | Parallel time (s) | Speedup | Efficiency | Cost (s) |",
        "| ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: |",
    ]
    for row in rows:
        lines.append(
            f"| {row['n']} | {row['threads']} | {row['prime_count']} | {row['serial_time_s']} | "
            f"{row['parallel_time_s']} | {row['speedup']} | {row['efficiency']} | {row['cost_s']} |"
        )
    path.write_text("\n".join(lines) + "\n", encoding="ascii")


def run_block_size_experiment(limit: int = EXPERIMENT_LIMIT, block_sizes: tuple[int, ...] = BLOCK_SIZES, threads: tuple[int, ...] = THREAD_COUNTS, trials: int = EXPERIMENT_TRIALS) -> list[dict[str, object]]:
    serial = binary("sieve_serial")
    openmp = binary("sieve_openmp")
    serial_samples = [run([str(serial), str(limit), "0", str(TIMING_REPETITIONS)], limit) for _ in range(trials)]
    serial_median_ms = statistics.median(float(sample["execution_time_ms"]) for sample in serial_samples)
    rows: list[dict[str, object]] = []

    for block_size in block_sizes:
        block_samples: dict[int, list[dict[str, object]]] = {}
        for thread_count in threads:
            samples = [
                run(
                    [str(openmp), str(limit), str(thread_count), "0", str(TIMING_REPETITIONS), str(block_size)],
                    limit,
                    thread_count,
                )
                for _ in range(trials)
            ]
            block_samples[thread_count] = samples

        baseline_median_ms = statistics.median(
            float(sample["execution_time_ms"]) for sample in block_samples[1]
        )

        for thread_count in threads:
            samples = block_samples[thread_count]
            prime_count = samples[0]["prime_count"]
            times_ms = [float(sample["execution_time_ms"]) for sample in samples]
            median_ms = statistics.median(times_ms)
            thread_scaling_speedup = baseline_median_ms / median_ms if median_ms > 0 else 0.0
            thread_scaling_efficiency = thread_scaling_speedup / thread_count if thread_count > 0 else 0.0
            serial_vs_openmp_speedup = serial_median_ms / median_ms if median_ms > 0 else 0.0
            rows.append({
                "n": limit,
                "block_size": block_size,
                "threads": thread_count,
                "prime_count": prime_count,
                "median_execution_time_ms": round(median_ms, 6),
                "serial_median_execution_time_ms": round(serial_median_ms, 6),
                "thread_scaling_speedup": round(thread_scaling_speedup, 6),
                "thread_scaling_efficiency": round(thread_scaling_efficiency, 6),
                "serial_vs_openmp_speedup": round(serial_vs_openmp_speedup, 6),
                "trial_count": trials,
                "times_ms": [round(time_ms, 6) for time_ms in times_ms],
            })

    return rows


def write_block_size_experiment(rows: list[dict[str, object]], csv_path: Path, json_path: Path) -> None:
    with csv_path.open("w", newline="", encoding="ascii") as output:
        writer = csv.DictWriter(
            output,
            fieldnames=[
                "n",
                "block_size",
                "threads",
                "prime_count",
                "median_execution_time_ms",
                "serial_median_execution_time_ms",
                "thread_scaling_speedup",
                "thread_scaling_efficiency",
                "serial_vs_openmp_speedup",
                "trial_count",
            ],
        )
        writer.writeheader()
        for row in rows:
            writer.writerow({
                "n": row["n"],
                "block_size": row["block_size"],
                "threads": row["threads"],
                "prime_count": row["prime_count"],
                "median_execution_time_ms": row["median_execution_time_ms"],
                "serial_median_execution_time_ms": row["serial_median_execution_time_ms"],
                "thread_scaling_speedup": row["thread_scaling_speedup"],
                "thread_scaling_efficiency": row["thread_scaling_efficiency"],
                "serial_vs_openmp_speedup": row["serial_vs_openmp_speedup"],
                "trial_count": row["trial_count"],
            })
    json_path.write_text(json.dumps(rows, indent=2), encoding="ascii")


