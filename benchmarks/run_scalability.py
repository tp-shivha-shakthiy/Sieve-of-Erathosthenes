def main() -> None:
    serial = binary("sieve_serial")
    openmp = binary("sieve_openmp")
    RESULTS_DIR.mkdir(exist_ok=True)
    summary_rows: list[dict[str, object]] = []
    trial_rows: list[dict[str, object]] = []

    for limit in LIMITS:
        serial_samples = measure([str(serial), str(limit), "0", str(TIMING_REPETITIONS)], limit)
        serial_times = seconds(serial_samples)
        serial_median = statistics.median(serial_times)
        for trial, elapsed in enumerate(serial_times, 1):
            trial_rows.append({"n": limit, "algorithm": "serial", "threads": 1, "trial": trial, "computation_time_s": f"{elapsed:.9f}"})

        for threads in THREAD_COUNTS:
            parallel_samples = measure(
                [str(openmp), str(limit), str(threads), "0", str(TIMING_REPETITIONS)], limit, threads
            )
            parallel_times = seconds(parallel_samples)
            parallel_median = statistics.median(parallel_times)
            metrics = derived_metrics(serial_median, parallel_median, threads)
            for trial, elapsed in enumerate(parallel_times, 1):
                trial_rows.append({"n": limit, "algorithm": "openmp", "threads": threads, "trial": trial, "computation_time_s": f"{elapsed:.9f}"})
            summary_rows.append({
                "n": limit,
                "threads": threads,
                "actual_threads": parallel_samples[-1]["actual_threads"],
                "prime_count": parallel_samples[-1]["prime_count"],
                "serial_time_s": f"{serial_median:.9f}",
                "parallel_time_s": f"{parallel_median:.9f}",
                "speedup": f"{metrics['speedup']:.6f}",
                "efficiency": f"{metrics['efficiency']:.6f}",
                "efficiency_percent": f"{metrics['efficiency_percent']:.4f}",
                "cost_s": f"{metrics['cost_s']:.9f}",
                "serial_stddev_s": f"{statistics.stdev(serial_times):.9f}",
                "parallel_stddev_s": f"{statistics.stdev(parallel_times):.9f}",
            })

    with (RESULTS_DIR / "benchmark.csv").open("w", newline="", encoding="ascii") as output:
        writer = csv.DictWriter(output, fieldnames=summary_rows[0].keys())
        writer.writeheader()
        writer.writerows(summary_rows)
    with (RESULTS_DIR / "benchmark_trials.csv").open("w", newline="", encoding="ascii") as output:
        writer = csv.DictWriter(output, fieldnames=trial_rows[0].keys())
        writer.writeheader()
        writer.writerows(trial_rows)

    compiler = subprocess.run(["g++", "--version"], capture_output=True, text=True, check=False)
    metadata = {
        "timestamp_utc": datetime.now(timezone.utc).isoformat(),
        "platform": platform.platform(),
        "processor": platform.processor(),
        "logical_cpu_count": os.cpu_count(),
        "compiler": compiler.stdout.splitlines()[0] if compiler.stdout else None,
        "optimization_flags": "-O2 -Wall -Wextra -std=c++17; OpenMP additionally uses -fopenmp",
        "timed_region": "allocation, initialization, base-prime generation where applicable, marking, and counting; JSON output excluded",
        "timing_units": "seconds",
        "statistic": "median of 7 measured samples after one warm-up",
        "in_program_timing_repetitions": TIMING_REPETITIONS,
        "thread_counts": THREAD_COUNTS,
        "limits": LIMITS,
        "omp_num_threads": os.environ.get("OMP_NUM_THREADS"),
        "omp_proc_bind": os.environ.get("OMP_PROC_BIND"),
        "omp_places": os.environ.get("OMP_PLACES"),
    }
    (RESULTS_DIR / "benchmark_metadata.json").write_text(json.dumps(metadata, indent=2), encoding="ascii")
    write_markdown(summary_rows, RESULTS_DIR / "benchmark_report.md")
    print(f"Wrote canonical benchmark bundle to {RESULTS_DIR}")


if __name__ == "__main__":
    if len(sys.argv) > 1 and sys.argv[1] == "--block-size-experiment":
        rows = run_block_size_experiment()
        write_block_size_experiment(
            rows,
            RESULTS_DIR / "block_size_sensitivity.csv",
            RESULTS_DIR / "block_size_sensitivity.json",
        )
        print(f"Wrote block-size experiment results to {RESULTS_DIR / 'block_size_sensitivity.csv'} and {RESULTS_DIR / 'block_size_sensitivity.json'}")
    elif len(sys.argv) > 1 and sys.argv[1] == "--scheduling-experiment":
        rows = run_scheduling_experiment()
        write_scheduling_experiment(
            rows,
            RESULTS_DIR / "scheduling_sensitivity.csv",
            RESULTS_DIR / "scheduling_sensitivity.json",
        )
        print(f"Wrote scheduling experiment results to {RESULTS_DIR / 'scheduling_sensitivity.csv'} and {RESULTS_DIR / 'scheduling_sensitivity.json'}")
    elif len(sys.argv) > 1 and sys.argv[1] == "--parallel-strategy-experiment":
        rows = run_parallel_strategy_experiment()
        write_parallel_strategy_experiment(
            rows,
            RESULTS_DIR / "parallel_strategy_comparison.csv",
            RESULTS_DIR / "parallel_strategy_comparison.json",
        )
        print(f"Wrote parallel strategy comparison results to {RESULTS_DIR / 'parallel_strategy_comparison.csv'} and {RESULTS_DIR / 'parallel_strategy_comparison.json'}")
    else:
        main()
